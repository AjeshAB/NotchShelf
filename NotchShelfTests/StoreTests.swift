    func testPausedHistoryHasNoCaptureTimerAndStopDisconnectsPreferences() throws {
        let prefs = preferences(), store = try store(prefs)
        store.start(); XCTAssertFalse(store.isPolling)
        prefs.clipboardEnabled = true; XCTAssertTrue(store.isPolling)
        prefs.clipboardEnabled = false; XCTAssertFalse(store.isPolling)
