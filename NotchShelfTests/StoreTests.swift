    }
    func testDragExportsMultipleFileURLsForFinder() throws {
        let urls = [URL(fileURLWithPath: "/tmp/A file.txt"), URL(fileURLWithPath: "/tmp/Second.pdf")]
        let items = FileDragView.draggingItems(for: urls, at: NSPoint(x: 45, y: 60))
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let writers = try items.map { try XCTUnwrap($0.item as? NSPasteboardWriting) }
        XCTAssertTrue(board.writeObjects(writers))
        let decoded = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        XCTAssertEqual(decoded, urls)
    }
    func testWholeFileTileReceivesClicksWithoutActivatingApp() throws {
        let view = FileDragView(frame: NSRect(x: 0, y: 0, width: 100, height: 82))
        XCTAssertTrue(view.acceptsFirstMouse(for: nil))
        XCTAssertTrue(view.hitTest(NSPoint(x: 50, y: 64)) === view)
        var selected = false, held = false
        view.onSelect = { selected = true }; view.onPress = { held = $0 }
        let down = try XCTUnwrap(NSEvent.mouseEvent(with: .leftMouseDown, location: NSPoint(x: 50, y: 64), modifierFlags: [], timestamp: 0, windowNumber: 0, context: nil, eventNumber: 0, clickCount: 1, pressure: 1))
        let up = try XCTUnwrap(NSEvent.mouseEvent(with: .leftMouseUp, location: NSPoint(x: 50, y: 64), modifierFlags: [], timestamp: 0.1, windowNumber: 0, context: nil, eventNumber: 1, clickCount: 1, pressure: 0))
        view.mouseDown(with: down); XCTAssertTrue(held)
        view.mouseUp(with: up); XCTAssertFalse(held); XCTAssertTrue(selected)
    }

    func testLegacyRawDuplicatesCollapseWithoutDeletingFiles() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let store = ShelfStore(root: root)
        store.add(data: Data("Repeated note".utf8), extension: "txt")
        var first = try XCTUnwrap(store.items.first); first.payloadHash = nil
        let firstURL = try XCTUnwrap(first.resolve())
        let secondFolder = store.filesDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: secondFolder, withIntermediateDirectories: true)
        let secondURL = secondFolder.appendingPathComponent("Drop.txt")
        try FileManager.default.copyItem(at: firstURL, to: secondURL)
        let second = ShelfItem(bookmark: try secondURL.bookmarkData(), originalPath: secondURL.path, name: "Drop.txt", managed: true)
        try JSONEncoder().encode([first, second]).write(to: root.appendingPathComponent("shelf.json"))
        let reopened = ShelfStore(root: root)
        XCTAssertEqual(reopened.items.count, 1)
        XCTAssertNotNil(reopened.items.first?.payloadHash)
        XCTAssertTrue(FileManager.default.fileExists(atPath: firstURL.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: secondURL.path))
        reopened.add(data: Data("Repeated note".utf8), extension: "txt")
        XCTAssertEqual(reopened.items.count, 1)
    }

    func testClearAllIncludesPinsAndPreservesCurrentClipboard() throws {
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(preferences(), board: board)
        board.setString("Current clipboard", forType: .string)
        let pinned = ClipboardEntry(kind: "text", text: "Pinned history"); pinned.pinned = true
        store.insert(pinned); store.insert(ClipboardEntry(kind: "text", text: "Unpinned history"))
        store.clearAll()
        XCTAssertTrue(store.entries.isEmpty)
        XCTAssertEqual(board.string(forType: .string), "Current clipboard")
    }
    func testClearShelfPersistsEmptyListWithoutRemovingSavedFiles() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let store = ShelfStore(root: root)
        store.add(data: Data("One".utf8), extension: "txt")
        store.add(data: Data("Two".utf8), extension: "txt")
        let files = store.items.compactMap { $0.resolve() }
        XCTAssertEqual(files.count, 2)
        store.clear()
        XCTAssertTrue(store.items.isEmpty)
        XCTAssertTrue(ShelfStore(root: root).items.isEmpty)
        for file in files { XCTAssertTrue(FileManager.default.fileExists(atPath: file.path)) }
    }

