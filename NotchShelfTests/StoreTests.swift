@MainActor
final class StoreTests: XCTestCase {
    private func preferences() -> Preferences {
        let defaults = UserDefaults(suiteName: UUID().uuidString)!
        return Preferences(defaults: defaults)
    }
    private func store(_ prefs: Preferences, board: NSPasteboard? = nil) throws -> ClipboardStore {
        let container = try ModelContainer(for: ClipboardEntry.self, configurations: ModelConfiguration(isStoredInMemoryOnly: true))
        return ClipboardStore(container: container, preferences: prefs, pasteboard: board ?? NSPasteboard.withUniqueName())
    }
    func testPrivatePasteboardMarkers() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(ClipboardStore.isPrivate([.string, .init(type)]))
        }
        XCTAssertFalse(ClipboardStore.isPrivate([.string, .rtf]))
    }
    func testHistoryIsOptIn() { XCTAssertFalse(preferences().clipboardEnabled) }
    func testExcludedAppsTrimWhitespace() {
        let prefs = preferences(); prefs.excludedApps = "  com.example.secret  \ncom.bank.app"
        XCTAssertTrue(prefs.excludes("com.example.secret")); XCTAssertFalse(prefs.excludes("com.example.other"))
    }
    func testDedupPreservesPin() throws {
        let store = try store(preferences())
        let first = ClipboardEntry(kind: "text", text: "hello")
        store.insert(first); store.togglePin(first)
        store.insert(ClipboardEntry(kind: "text", text: "hello", sourceName: "New app"))
        XCTAssertEqual(store.entries.count, 1); XCTAssertTrue(store.entries[0].pinned)
        XCTAssertEqual(store.entries[0].sourceName, "New app")
    }
    func testRetentionPreservesPinsAndRemovesOldEntries() throws {
        let prefs = preferences(); prefs.historyDays = 1
        let store = try store(prefs)
        let pinned = ClipboardEntry(kind: "text", text: "pinned"); pinned.pinned = true
        pinned.timestamp = .distantPast; store.insert(pinned)
        let expired = ClipboardEntry(kind: "text", text: "expired"); expired.timestamp = .distantPast
        store.insert(expired); store.insert(ClipboardEntry(kind: "text", text: "new"))
        XCTAssertEqual(Set(store.entries.map(\.text)), ["pinned", "new"])
    }
    func testCountLimit() throws {
        let prefs = preferences(); prefs.historyLimit = 2
        let store = try store(prefs)
        for i in 0..<5 { store.insert(ClipboardEntry(kind: "text", text: "\(i)")) }
        XCTAssertEqual(store.entries.count, 2)
        XCTAssertEqual(Set(store.entries.map(\.text)), ["3", "4"])
    }
    func testConcealedDataNeverCaptured() throws {
        let prefs = preferences(); prefs.clipboardEnabled = true
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(prefs, board: board)
        board.clearContents(); board.setString("secret", forType: .string)
        board.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        store.poll(); XCTAssertTrue(store.entries.isEmpty)
        board.clearContents(); board.setString("ordinary", forType: .string)
        store.poll(); XCTAssertEqual(store.entries.first?.text, "ordinary")
    }
    func testOwnCopyDoesNotRecapture() throws {
        let prefs = preferences(); prefs.clipboardEnabled = true
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(prefs, board: board)
        XCTAssertTrue(store.write(ClipboardEntry(kind: "text", text: "copied")))
        store.poll(); XCTAssertTrue(store.entries.isEmpty)
        XCTAssertEqual(board.string(forType: .string), "copied")
    }
    func testRichTextIncludedInHash() {
        let plain = ClipboardEntry(kind: "text", text: "Hello")
        let rich = ClipboardEntry(kind: "text", text: "Hello", richText: Data("RTF".utf8))
        XCTAssertNotEqual(plain.contentHash, rich.contentHash)
    }
    func testClearKeepsPins() throws {
        let store = try store(preferences())
        let pin = ClipboardEntry(kind: "text", text: "keep"); pin.pinned = true
        store.insert(pin); store.insert(ClipboardEntry(kind: "text", text: "remove"))
        store.clearUnpinned(); XCTAssertEqual(store.entries.map(\.text), ["keep"])
    }
    func testShelfPersistsManagedCopyAndRemovalKeepsFile() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let original = root.appendingPathComponent("hello.txt"); try Data("Hello".utf8).write(to: original)
        let store = ShelfStore(root: root.appendingPathComponent("app"))
        store.add([original], copy: true)
        XCTAssertEqual(store.items.count, 1)
        let stored = try XCTUnwrap(store.items.first?.resolve())
        XCTAssertNotEqual(stored, original)
        let reopened = ShelfStore(root: root.appendingPathComponent("app"))
        XCTAssertEqual(reopened.items.first?.resolve(), stored)
        reopened.remove(Set(reopened.items.map(\.id)))
        XCTAssertTrue(FileManager.default.fileExists(atPath: original.path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: stored.path))
        XCTAssertTrue(ShelfStore(root: root.appendingPathComponent("app")).items.isEmpty)
    }
    func testRepeatedTemporaryDropsStayUniqueAcrossRelaunch() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let file = root.appendingPathComponent("Example.txt")
        try Data("Example".utf8).write(to: file)
        let storage = root.appendingPathComponent("app")
        let store = ShelfStore(root: storage)
        store.add([file, file]); XCTAssertEqual(store.items.count, 1)
        let reopened = ShelfStore(root: storage)
        reopened.add([file]); XCTAssertEqual(reopened.items.count, 1)
    }
    func testDroppingSourceAliasDoesNotDuplicate() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
