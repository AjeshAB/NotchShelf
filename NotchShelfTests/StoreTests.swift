    func testNoOpRetentionDoesNotPublishOrReloadHistory() throws {
        let store = try store(preferences())
        store.insert(ClipboardEntry(kind: "text", text: "Recent"))
        var updates = 0
        let subscription = store.$entries.dropFirst().sink { _ in updates += 1 }
        store.prune(); store.prune()
        XCTAssertEqual(updates, 0)
        withExtendedLifetime(subscription) {}
    }
    func testStreamingHashPreservesExistingDedupIdentity() {
        let rich = Data("RTF".utf8), image = Data(repeating: 7, count: 1_000_000)
        let paths = ["/tmp/a b.txt", "/tmp/日本語.txt"]
        var legacy = Data()
        for field in [Data("image".utf8), Data("A note".utf8), rich, image] + paths.map({ Data($0.utf8) }) {
            legacy.append(Data("\(field.count):".utf8)); legacy.append(field)
        }
        let expected = SHA256.hash(data: legacy).map { String(format: "%02x", $0) }.joined()
        XCTAssertEqual(ClipboardEntry.hash(kind: "image", text: "A note", richText: rich, imageData: image, paths: paths), expected)
    }
    func testVSCodeFilesCaptureAndRoundTripToNativeAndCodeFormats() throws {
        let prefs = preferences(); prefs.clipboardEnabled = true
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(prefs, board: board)
        let urls = [URL(fileURLWithPath: "/tmp/A file.swift"), URL(fileURLWithPath: "/tmp/日本語#%.txt")]
        let data = Data(urls.map(\.absoluteString).joined(separator: "\n").utf8)
        board.clearContents()
        board.setData(data, forType: .init("code/file-list"))
        store.poll()
        let entry = try XCTUnwrap(store.entries.first)
        XCTAssertEqual(entry.kind, "files")
        XCTAssertEqual(entry.filePaths, urls.map(\.path))
        XCTAssertTrue(store.write(entry))
        XCTAssertEqual(board.data(forType: .init("code/file-list")), data)
        XCTAssertEqual(board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], urls)
        store.poll(); XCTAssertEqual(store.entries.count, 1)
    }
    func testVSCodeFilesIgnoreRemoteResourcesAndDuplicates() throws {
        let prefs = preferences(); prefs.clipboardEnabled = true
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(prefs, board: board)
        board.clearContents()
        board.setData(Data("file:///tmp/a.txt\nfile:///tmp/a.txt\nvscode-remote://ssh-remote+host/tmp/b.txt\nfile://server/tmp/c.txt\nhttps://example.com/file\ninvalid".utf8), forType: .init("code/file-list"))
        store.poll()
        XCTAssertEqual(store.entries.first?.filePaths, ["/tmp/a.txt"])
    }
    func testInvalidVSCodeDataFallsBackToTextAndHonorsPrivacy() throws {
        let prefs = preferences(); prefs.clipboardEnabled = true
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let store = try store(prefs, board: board)
        board.clearContents()
        board.setData(Data([0xff]), forType: .init("code/file-list"))
        board.setString("Copied code", forType: .string)
        store.poll(); XCTAssertEqual(store.entries.first?.text, "Copied code")
        board.clearContents()
        board.setData(Data("file:///tmp/private.txt".utf8), forType: .init("code/file-list"))
        board.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        store.poll(); XCTAssertEqual(store.entries.count, 1)
    }
