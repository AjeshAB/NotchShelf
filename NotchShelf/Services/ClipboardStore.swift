import AppKit
import SwiftData
import Combine

@MainActor
final class ClipboardStore: ObservableObject {
    private static let codeFileList = NSPasteboard.PasteboardType("code/file-list")
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var error: String?
    private let context: ModelContext
    private let preferences: Preferences
    private var timer: Timer?
    private var retentionTimer: Timer?
    private var preferenceSubscription: AnyCancellable?
    private var running = false
    var isPolling: Bool { timer != nil }
    private var lastCount: Int
    private let pasteboard: NSPasteboard
    init(container: ModelContainer, preferences: Preferences, pasteboard: NSPasteboard = .general) {
        context = ModelContext(container); self.preferences = preferences; self.pasteboard = pasteboard
        lastCount = pasteboard.changeCount
        context.autosaveEnabled = false
        reload()
    }
    func start() {
        guard !running else { return }
        running = true
        preferenceSubscription = preferences.$clipboardEnabled.removeDuplicates().sink { [weak self] enabled in
            self?.setCaptureEnabled(enabled)
        }
        retentionTimer = Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.prune() }
        }
        retentionTimer?.tolerance = 15
    }
    private func setCaptureEnabled(_ enabled: Bool) {
        timer?.invalidate(); timer = nil
        lastCount = pasteboard.changeCount
        guard running, enabled else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }
    func stop() {
        running = false
        timer?.invalidate(); timer = nil
        retentionTimer?.invalidate(); retentionTimer = nil
        preferenceSubscription?.cancel(); preferenceSubscription = nil
    }
    static func isPrivate(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        let protected: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return types.contains { protected.contains($0.rawValue) }
    }
    func poll() {
        guard pasteboard.changeCount != lastCount else { return }
        lastCount = pasteboard.changeCount
        guard preferences.clipboardEnabled, !Self.isPrivate(pasteboard.types ?? []) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        guard !preferences.excludes(app?.bundleIdentifier) else { return }
        let name = app?.localizedName ?? "Unknown app", bundle = app?.bundleIdentifier ?? ""
        let entry: ClipboardEntry
        let urls = fileURLs()
        if !urls.isEmpty {
            entry = ClipboardEntry(kind: "files", filePaths: urls.map(\.path), sourceName: name, sourceBundleID: bundle)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= 25_000_000 {
            entry = ClipboardEntry(kind: "image", imageData: data, sourceName: name, sourceBundleID: bundle)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= 2_000_000 {
            let isLink = URL(string: text).map { ["https", "http"].contains($0.scheme?.lowercased() ?? "") && $0.host != nil } ?? false
            let rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= 5_000_000 ? $0 : nil }
            entry = ClipboardEntry(kind: isLink ? "link" : "text", text: text, richText: rtf, sourceName: name, sourceBundleID: bundle)
        } else { return }
        insert(entry)
    }
    private func fileURLs() -> [URL] {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return urls
        }
        // VS Code's native clipboard service writes newline-separated UTF-8 URIs.
        guard let data = pasteboard.data(forType: Self.codeFileList), data.count <= 2_000_000,
              let value = String(data: data, encoding: .utf8) else { return [] }
        var seen = Set<String>()
        return value.split(separator: "\n").compactMap { line in
            guard let url = URL(string: String(line)), url.isFileURL,
                  url.host == nil || url.host == "" || url.host == "localhost",
                  url.query == nil, url.fragment == nil, url.path.hasPrefix("/"),
                  !url.path.contains("\0"), seen.insert(url.path).inserted else { return nil }
            return URL(fileURLWithPath: url.path)
        }
    }
    func insert(_ entry: ClipboardEntry) {
        if let existing = entries.first(where: { $0.contentHash == entry.contentHash }) {
            existing.timestamp = entry.timestamp
            existing.sourceName = entry.sourceName; existing.sourceBundleID = entry.sourceBundleID
        } else { context.insert(entry) }
        persist(); prune()
    }
    func prune(now: Date = Date()) {
        let cutoff = now.addingTimeInterval(-Double(max(1, preferences.historyDays)) * 86_400)
        let unpinned = entries.filter { !$0.pinned }.sorted { $0.timestamp > $1.timestamp }
        let expired = unpinned.enumerated().filter { $0.offset >= max(1, preferences.historyLimit) || $0.element.timestamp < cutoff }
        guard !expired.isEmpty else { return }
        for (_, entry) in expired { context.delete(entry) }
        persist()
    }
    func togglePin(_ entry: ClipboardEntry) { entry.pinned.toggle(); persist() }
    func delete(_ entry: ClipboardEntry) { context.delete(entry); persist() }
    func clearAll() { for entry in entries { context.delete(entry) }; persist() }
    func clearUnpinned() { for entry in entries where !entry.pinned { context.delete(entry) }; persist() }
    func write(_ entry: ClipboardEntry) -> Bool {
        pasteboard.clearContents()
        let success: Bool
        switch entry.kind {
        case "files":
            let urls = entry.filePaths.map { URL(fileURLWithPath: $0) }
            success = pasteboard.writeObjects(urls as [NSURL])
            if success {
                pasteboard.setData(Data(urls.map(\.absoluteString).joined(separator: "\n").utf8), forType: Self.codeFileList)
            }
        case "image":
            if let data = entry.imageData {
                // Preserve the captured bytes instead of decoding/re-encoding a full image.
                let png = data.starts(with: [0x89, 0x50, 0x4E, 0x47])
                success = pasteboard.setData(data, forType: png ? .png : .tiff)
            } else { success = false }
        default:
            success = pasteboard.setString(entry.text, forType: .string)
            if let rtf = entry.richText { pasteboard.setData(rtf, forType: .rtf) }
        }
        lastCount = pasteboard.changeCount
        return success
    }
    private func persist() {
        guard context.hasChanges else { return }
        do { try context.save(); reload() } catch { self.error = "Could not save clipboard history: \(error.localizedDescription)" }
    }
    private func reload() {
        do { entries = try context.fetch(FetchDescriptor<ClipboardEntry>(sortBy: [SortDescriptor(\.timestamp, order: .reverse)])) }
        catch { self.error = error.localizedDescription }
    }
}
